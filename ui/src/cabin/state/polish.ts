/** Polish cardinal forms, including 12–14 and numbers such as 22 and 112. */
export function polishCount(count: number, one: string, few: string, many: string): string {
  const n = Math.abs(Math.trunc(count))
  const form = n === 1 ? one : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 12 || n % 100 > 14) ? few : many
  return `${count} ${form}`
}

